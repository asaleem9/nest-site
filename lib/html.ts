// Minimal HTML entity escaping for user-provided values that end up inside
// generated HTML (the contact email). Covers text and attribute contexts.
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
